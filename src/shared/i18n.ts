/** 所有语言的全部文字。导出供一致性测试使用。 */
export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { zh, en };

export function isLocale(value: unknown): value is Locale {
  return value === "zh" || value === "en";
}

/** 启动时使用的语言：中文系统用中文，其他一律英文。 */
export function systemLocale(): Locale {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** 当前界面语言。在模板或 computed 中读取它，语言变化时会重新渲染。 */
export const locale = ref<Locale>(systemLocale());

/** 取当前语言的文字，并填入其中的 `{占位符}`。 */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const message = MESSAGES[locale.value][key];
  if (!params) return message;
  return message.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}
